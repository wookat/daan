// ---------------------------------------------------------------- checks
function parseColor(str) {
  const s = str.trim();
  const hex = s.match(/^#([0-9a-f]{6})$/i);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return [n >> 16, (n >> 8) & 255, n & 255, 1];
  }
  const rgba = s.match(/^rgba?\(([^)]+)\)$/i);
  if (rgba) {
    const p = rgba[1].split(',').map((x) => parseFloat(x));
    return [p[0], p[1], p[2], p[3] ?? 1];
  }
  return null;
}

function luminance([r, g, b]) {
  const f = (c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

export function contrast(fg, bg) {
  const a = parseColor(fg);
  const b = parseColor(bg);
  if (!a || !b) throw new Error(`contrast(): cannot parse ${fg} / ${bg}`);
  const l1 = luminance(a);
  const l2 = luminance(b);
  return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

// SPEC §2.6：正文 ≥4.5，图标/边框 ≥3。
const CONTRAST_RULES = [
  ['ink', 'card', 4.5], ['ink', 'bg', 4.5],
  ['ink-2', 'card', 4.5], ['ink-2', 'bg', 4.5],
  ['ink-3', 'card', 4.5], ['ink-3', 'bg', 4.5],
  ['brand-text', 'card', 4.5], ['brand-text', 'brand-soft', 4.5],
  ['ok-strong', 'card', 4.5], ['ok-strong', 'ok-soft', 4.5],
  ['bad-strong', 'card', 4.5], ['bad-strong', 'bad-soft', 4.5],
  ['warn-strong', 'card', 4.5], ['warn-strong', 'warn-soft', 4.5],
  ['info-strong', 'card', 4.5], ['info-strong', 'info-soft', 4.5],
  ['on-brand', 'brand', 4.5],
  ['on-brand', 'ok-strong', 4.5, 'light'], ['on-brand', 'bad-strong', 4.5, 'light'], ['on-brand', 'warn-strong', 4.5, 'light'],
  ['brand', 'card', 3], ['ok', 'card', 3], ['bad', 'card', 3], ['line-strong', 'card', 1.2],
];

export function runChecks(tree, flat, { zalizeCss }) {
  const errors = [];
  const byName = Object.fromEntries(flat.map((t) => [t.name, t]));
  const semByName = Object.fromEntries(flat.filter((t) => t.group === 'sem').map((t) => [t.name, t]));

  for (const [fg, bg, min, only] of CONTRAST_RULES) {
    for (const mode of ['light', 'dark']) {
      if (only && only !== mode) continue;
      const f = semByName[fg];
      const b = semByName[bg];
      if (!f || !b) { errors.push(`contrast rule references unknown token ${fg}/${bg}`); continue; }
      const ratio = contrast(f[mode], b[mode]);
      if (ratio < min) errors.push(`contrast ${mode} --${fg} on --${bg} = ${ratio.toFixed(2)} < ${min}`);
    }
  }

  for (const t of flat.filter((x) => x.group === 'fs')) {
    const px = parseFloat(t.light);
    if (!Number.isInteger(px * 2)) errors.push(`--fs-${t.name} ${t.light} ×2 rpx 不是整数`);
    if ((px * 2) % 2 !== 0) errors.push(`--fs-${t.name} ${t.light} rpx 换算为奇数`);
    if (px < 12) errors.push(`--fs-${t.name} ${t.light} < 12px（≤11px 一律禁止）`);
  }

  const SP_OK = new Set([4, 8, 12, 16, 20, 24, 32, 40, 48]);
  for (const t of flat.filter((x) => x.group === 'sp')) {
    if (!SP_OK.has(parseFloat(t.light))) errors.push(`--sp-${t.name} ${t.light} 不在间距白名单`);
  }
  const R_OK = new Set([6, 10, 14, 20, 999]);
  for (const t of flat.filter((x) => x.group === 'r')) {
    if (!R_OK.has(parseFloat(t.light))) errors.push(`--r-${t.name} ${t.light} 不在圆角白名单`);
  }
  for (const t of flat.filter((x) => x.group === 'sem' && x.name.startsWith('fw-'))) {
    if (![400, 500, 600].includes(Number(t.light))) errors.push(`${t.cssName} ${t.light} 字重只允许 400/500/600`);
  }
  for (const t of flat.filter((x) => x.group === 'sem' && x.name.startsWith('sh-'))) {
    if (t.dark !== 'none') errors.push(`${t.cssName} 深色必须为 none（深色不用阴影）`);
  }

  // @zalize/brand 一致：本仓 brand 500/600/700 = 上游 600/700/800，50–400 同阶
  if (zalizeCss) {
    const up = {};
    for (const m of zalizeCss.matchAll(/--zl-brand-(\d+):\s*(#[0-9a-f]{6})/gi)) up[m[1]] = m[2].toLowerCase();
    const map = { 50: '50', 100: '100', 200: '200', 300: '300', 400: '400', 500: '600', 600: '700', 700: '800' };
    for (const [ours, theirs] of Object.entries(map)) {
      const v = tree.color.brand[ours]?.$value?.toLowerCase();
      if (up[theirs] && v !== up[theirs]) errors.push(`color.brand.${ours} ${v} ≠ @zalize/brand --zl-brand-${theirs} ${up[theirs]}`);
    }
  }

  // SPEC open question #1 已定：品牌主色 = color.inkblue.500（书案墨蓝 #1e4a6b）。
  if (byName.brand?.light !== '#1e4a6b') errors.push('--brand 必须为 #1e4a6b（书案墨蓝，SPEC open question #1 已定）');
  return errors;
}

// ---------------------------------------------------------------- main
export async function generate(tree = JSON.parse(fs.readFileSync(TOKENS_PATH, 'utf8'))) {
  const flat = flatten(tree);
  const icons = loadIconPaths();
  return {
    tree,
    flat,
    files: {
      [OUTPUTS.scss]: emitScss(flat),
      [OUTPUTS.css]: emitCss(flat),
      [OUTPUTS.wxss]: emitWxss(flat),
      [OUTPUTS.moduleMetaJs]: emitModuleMetaJs(tree),
      [OUTPUTS.moduleMetaTs]: emitModuleMetaTs(tree),
      [OUTPUTS.iconPathsTs]: emitIconPathsTs(icons),
    },
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const { tree, flat, files } = await generate();
  const zalizePath = path.join(H5, 'static/brand/zalize-tokens.css');
  const zalizeCss = fs.existsSync(zalizePath) ? fs.readFileSync(zalizePath, 'utf8') : '';
  const errors = runChecks(tree, flat, { zalizeCss });

  if (check) {
    for (const [file, content] of Object.entries(files)) {
      const rel = path.relative(ROOT, file);
      if (!fs.existsSync(file)) errors.push(`${rel} 不存在，先运行 node tools/design-tokens/build.mjs`);
      else if (fs.readFileSync(file, 'utf8') !== content) errors.push(`${rel} 与 tokens.json 不一致，运行 node tools/design-tokens/build.mjs 并提交`);
    }
  }
  if (errors.length) {
    console.error(`design-tokens ${check ? '--check' : 'build'} 失败：\n  - ${errors.join('\n  - ')}`);
    process.exit(1);
  }
  if (!check) {
    for (const [file, content] of Object.entries(files)) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      console.log('wrote', path.relative(ROOT, file));
    }
  } else {
    console.log(`design-tokens --check ok（${flat.length} tokens，${Object.keys(files).length} 个生成文件一致）`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
