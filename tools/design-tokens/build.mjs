// ---------------------------------------------------------------- emitters
const decl = (indent, name, value) => `${indent}${name}: ${value};`;

function cssBlock(selector, lines) {
  return `${selector} {\n${lines.join('\n')}\n}`;
}

function lightDecls(flat) {
  const sem = flat.filter((t) => t.group === 'sem' || t.group === 'lh');
  const scale = flat.filter((t) => ['fs', 'sp', 'r', 'dur', 'ease', 'icon', 'z', 'bp'].includes(t.group));
  const comp = flat.filter((t) => t.group === 'comp');
  const mod = flat.filter((t) => t.group === 'mod');
  return [
    '  /* semantic */',
    ...sem.map((t) => decl('  ', t.cssName, t.light)),
    '  /* scale */',
    ...scale.map((t) => decl('  ', t.cssName, t.light)),
    '  /* component */',
    ...comp.map((t) => decl('  ', t.cssName, t.light)),
    '  /* module */',
    ...mod.map((t) => decl('  ', t.cssName, t.light)),
  ];
}

function darkDecls(flat) {
  return flat.filter((t) => t.dark !== t.light).map((t) => decl('  ', t.cssName, t.dark));
}

