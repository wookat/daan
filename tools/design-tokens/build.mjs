  const body = JSON.stringify(Object.fromEntries(moduleEntries(tree).map((m) => [m.key, m])), null, 2);
  return `${JS_HEADER}\n// 模块元数据单一来源：颜色只给 CSS 变量名，wxml 用 style="color:{{m.color}}" 即可自动跟随深色。\n\nexport interface ModuleMeta {\n  key: string;\n  label: string;\n  short: string;\n  icon: string;\n  color: string;\n  soft: string;\n  hex: string;\n  softHex: string;\n  softHexDark: string;\n}\n\nexport const MODULES: Record<string, ModuleMeta> = ${body};\n${MODULE_HELPERS.replace('export function moduleMeta(key)', 'export function moduleMeta(key: string): ModuleMeta').replace('export function moduleLabel(key)', 'export function moduleLabel(key: string): string')}`;
