// ---------------------------------------------------------------- resolve
function isToken(node) {
  return node && typeof node === 'object' && '$value' in node;
}

function getPath(tree, dotted) {
  return dotted.split('.').reduce((n, k) => (n == null ? undefined : n[k]), tree);
}

function resolveValue(tree, value, seen = new Set()) {
  if (Array.isArray(value)) return value;
  if (typeof value !== 'string') return value;
  return value.replace(/\{([a-z0-9.-]+)\}/gi, (_, ref) => {
    if (seen.has(ref)) throw new Error(`circular token reference: ${ref}`);
    const target = getPath(tree, ref);
    if (!isToken(target)) throw new Error(`unresolved token reference: {${ref}}`);
    return String(resolveValue(tree, target.$value, new Set([...seen, ref])));
  });
}

function fmt(type, value) {
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`;
  return String(value);
}

/** 展平成 [{ group, name, cssName, type, light, dark, lineHeight, meta }] */
export function flatten(tree) {
  const out = [];
  for (const [group, node] of Object.entries(tree)) {
    if (group.startsWith('$') || group === 'color') continue;
    for (const [name, tok] of Object.entries(node)) {
      if (name.startsWith('$') || !isToken(tok)) continue;
      const light = fmt(tok.$type, resolveValue(tree, tok.$value));
      const dark = tok.$dark != null ? fmt(tok.$type, resolveValue(tree, tok.$dark)) : light;
      // sem/comp 不带组前缀（--brand / --btn-h-lg），其余带（--fs-body / --sp-16 / --mod-ziliao）
      const cssName = group === 'sem' || group === 'comp' ? `--${name}` : `--${group}-${name}`;
      out.push({ group, name, cssName, type: tok.$type, light, dark, lineHeight: tok.$lineHeight, meta: tok });
      if (group === 'mod') {
        out.push({
          group, name: `${name}-soft`, cssName: `--mod-${name}-soft`, type: 'color',
          light: resolveValue(tree, tok.$soft), dark: resolveValue(tree, tok.$softDark ?? tok.$soft), meta: tok,
        });
      }
      if (tok.$lineHeight != null) {
        out.push({ group: 'lh', name, cssName: `--lh-${name}`, type: 'number', light: String(tok.$lineHeight), dark: String(tok.$lineHeight) });
      }
    }
  }
  return out;
}

