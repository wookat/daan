// kg-* 组件文档生成器：扫 miniprogram/components/*/index.ts 的 properties/observers/
// methods + 头部注释，产出 docs/kg-components.md（GENERATED，勿手改）。
// 用法：node tools/kg-docs/gen.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const cdir = join(root, 'miniapp-native/miniprogram/components');
const out = join(root, 'miniapp-native/docs/kg-components.md');

// index.ts 顶部注释块第一行作为组件简介；properties {k: {type,value}} 抽属性表
const rows = [];
for (const name of readdirSync(cdir).sort()) {
  const ts = join(cdir, name, 'index.ts');
  const wxml = join(cdir, name, 'index.wxml');
  let src = '';
  try {
    src = readFileSync(ts, 'utf-8');
  } catch {
    continue;
  }
  const head = /^\s*\/\/\s*(.+)/.exec(src);
  const desc = head ? head[1].trim() : '';
  const propsBlock = /properties\s*:\s*\{([\s\S]*?)\n\s*\},?/.exec(src);
  const props = [];
  if (propsBlock) {
    const re = /(\w+)\s*:\s*\{\s*type\s*:\s*(\w+)[^}]*?value\s*:\s*([^,}\n]+)/g;
    let m;
    while ((m = re.exec(propsBlock[1]))) props.push({ name: m[1], type: m[2], def: m[3].trim() });
  }
  const events = [...src.matchAll(/triggerEvent\(\s*['"]([\w:-]+)['"]/g)].map((m) => m[1]);
  rows.push({ name, desc, props, events: [...new Set(events)] });
}

const lines = [
  '# kg-* 组件库',
  '',
  '> GENERATED by `tools/kg-docs/gen.mjs`，不要手改。',
  `> 共 ${rows.length} 个组件，位于 \`miniprogram/components/\`，全部消费 tokens.generated.wxss 的设计变量。`,
  '',
];
for (const r of rows) {
  lines.push(`## ${r.name}`);
  if (r.desc) lines.push('', r.desc);
  if (r.props.length) {
    lines.push('', '| 属性 | 类型 | 默认值 |', '| --- | --- | --- |');
    for (const p of r.props) lines.push(`| ${p.name} | ${p.type} | ${p.def} |`);
  }
  if (r.events.length) lines.push('', '事件：' + r.events.map((e) => '`' + e + '`').join(' '));
  lines.push('');
}
writeFileSync(out, lines.join('\n'));
console.log(`✓ ${out}（${rows.length} 个组件）`);
