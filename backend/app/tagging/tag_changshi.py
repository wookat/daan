# ---------------- taxonomy ----------------

def load_taxonomy(path):
    with open(path, encoding="utf-8") as f:
        t = json.load(f)
    mod = next(m for m in t["modules"] if m["key"] == "changshi")
    groups = {}       # group_code -> [topic codes]
    alias2group = {}  # submodule alias -> group_code
    all_topics = []
    for g in mod["groups"]:
        codes = [tp["code"] for tp in g["topics"]]
        groups[g["code"]] = codes
        all_topics += codes
        for a in g.get("aliases", []):
            alias2group[a] = g["code"]
        alias2group[g["name"]] = g["code"]
    return groups, alias2group, all_topics

