COMPILED = {c: [(re.compile(p), w) for p, w in lex] for c, lex in LEX.items()}
RE_KAOCHA = re.compile(r"本题(?:主要)?考[查察][“《]?([^。，,.；;、”》\s]{1,20}?)[”》]?(?:并选|。|，|$)")
# “朝代+引号人名/名物”句式：古代史人物轶事题的强特征
RE_DYNASTY_Q = re.compile(
    r"^(西周|东周|春秋|战国|秦代|西汉|东汉|汉代|三国|西晋|东晋|南朝|北朝|南北朝|北魏|隋代|唐代|五代|北宋|南宋|宋代|辽代|金代|元代|明代|清代|商代|夏代)[“\"‘]")


# 数据噪声：解析与题干不属同一题（言语/数量/判断推理解析串入）
RE_NOISE = re.compile(r"语句排序|逻辑填空|词句理解|意图判断|片段阅读|方程法|周期相遇|观察选项特征|确定首句|本题考察词句|本题考察?言语|和差倍比|几何问题|勾股定理|将选项与文段一一对应|第一空|第二空")


def classify(q, groups, alias2group, all_topics):
    if RE_NOISE.search(q.get("explanation") or ""):
        return "UNKNOWN", 0.0, "rule"
    text = (q.get("question") or "") + " " + (q.get("options") or "") + " " + (q.get("explanation") or "")
    sub = (q.get("submodule") or "").strip()
    group = alias2group.get(sub)
    candidates = groups[group] if group else all_topics

    # 显式“本题考查X”
    kaocha_topic = None
    kaocha_group = None
    m = RE_KAOCHA.search(q.get("explanation") or "")
    if m:
        mapped = KAOCHA_MAP.get(m.group(1))
        if mapped:
            if mapped in all_topics:
                kaocha_topic = mapped
            elif mapped in groups:
                kaocha_group = mapped

    if kaocha_topic:
        # submodule 组约束一致或无约束时直接采信
        if not group or kaocha_topic in candidates:
            return kaocha_topic, 0.95, "rule"
        # 显式声明与 submodule 组冲突：宁缺勿错
        return "UNKNOWN", 0.0, "rule"
    if kaocha_group:
        if group and kaocha_group != group:
            return "UNKNOWN", 0.0, "rule"
        candidates = groups[kaocha_group]
        group = kaocha_group

    # 窄义 submodule 直接指向具体考点时加权
    sub_topic = KAOCHA_MAP.get(sub)

    # 古代史轶事题强特征：题干以“朝代+引号”开头
    dynasty_hit = bool(RE_DYNASTY_Q.search((q.get("question") or "").strip()))

    # 关键词计分
    scores = {}
    for c in candidates:
        s = 0
        for pat, w in COMPILED[c]:
            n = len(pat.findall(text))
            if n:
                s += w * min(n, 3)
        if s:
            scores[c] = s
    if sub_topic and sub_topic in candidates:
        scores[sub_topic] = scores.get(sub_topic, 0) + 4
    if dynasty_hit and "CS-LS-01" in candidates:
        # 仅当文学/文化特征不明显时才倾向古代史
        if max(scores.get("CS-LS-04", 0), scores.get("CS-LS-05", 0)) < 6:
            scores["CS-LS-01"] = scores.get("CS-LS-01", 0) + 6
    if not scores:
        return "UNKNOWN", 0.0, "rule"
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    best, bs = ranked[0]
    second = ranked[1][1] if len(ranked) > 1 else 0
    margin = bs - second
    if bs >= 8 and margin >= 4:
        conf = 0.9
    elif bs >= 5 and margin >= 2:
        conf = 0.75
    elif (bs >= 4 and margin >= 1) or (group and bs >= 2):
        conf = 0.6
    else:
        return "UNKNOWN", 0.0, "rule"
    if group:  # submodule 约束下更可信
        conf = min(0.95, conf + 0.05)
    return best, conf, "rule"


def main():
    tax_path, in_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    groups, alias2group, all_topics = load_taxonomy(tax_path)
    dist = Counter()
    with open(in_path, encoding="utf-8") as f, open(out_path, "w", encoding="utf-8") as out:
        for line in f:
            q = json.loads(line)
            tag, conf, method = classify(q, groups, alias2group, all_topics)
            dist[tag] += 1
            out.write(json.dumps({"id": q["id"], "tag3": tag, "confidence": conf, "method": method}, ensure_ascii=False) + "\n")
    total = sum(dist.values())
    for k, v in dist.most_common():
        print(f"{k}\t{v}\t{v/total:.1%}")
    print("TOTAL", total)


if __name__ == "__main__":
    main()
